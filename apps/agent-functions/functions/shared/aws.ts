// Access to the AWS case/client API and documents API, live or mock.
//
// Both modes return the upstream's own response shapes (`Upstream*` types), so
// the adapters in adapters.ts convert live and mock data the same way.

import evalCases from "./fixtures/eval-cases.json" with { type: "json" };
import solomRec from "./fixtures/solom-rec.json" with { type: "json" };
import stavbyFiser from "./fixtures/stavby-fiser.json" with { type: "json" };
import unhappy from "./fixtures/unhappy.json" with { type: "json" };
import {
  AWS_MOCK,
  API_SECRET,
  API_URL,
  type GlobalsContext,
  getGlobalUrl,
  isSwitchOn,
} from "./config.ts";

const TIMEOUT_MS = 8000;

// openapi-case-client.yaml `Case`.
export type UpstreamCase = {
  case_id: string;
  client_id: string;
  status: string;
  created_at: string;
  metadata?: Record<string, unknown>;
};

// openapi-case-client.yaml `Client`.
export type UpstreamClient = {
  client_id: string;
  ico: string;
  dic?: string;
  name: string;
  legal_form?: string;
  address?: string;
  status: string;
  contacts?: Array<{ name?: string; role?: string; email?: string; phone?: string; preferred_channel?: string }>;
  signatories?: Array<{ name?: string; function?: string; authorized?: boolean }>;
  kyc?: { status?: string; checked_at?: string };
  source?: string;
};

// documents API `listCaseDocuments` item.
export type UpstreamDocumentSummary = {
  document_id: string;
  title: string;
  label: string;
  label_status?: string;
  processing_status: string;
  page_count: number;
};

// documents API `getDocumentForValidation`. `text` separates pages with a form feed.
export type UpstreamDocument = UpstreamDocumentSummary & {
  case_id?: string;
  description?: string | null;
  text: string;
  confidence?: number | null;
  pages_failed?: number[];
};

// documents API `getDocumentSignatures` item. `role` is provider (SGEF),
// borrower, supplier, guarantor or insurer.
export type UpstreamSignature = {
  signature_id: string;
  page: number;
  bbox?: number[] | null;
  detector?: string;
  detection_score?: number;
  role: string;
  role_source?: string;
  role_evidence?: string;
  crop_url?: string | null;
  phash?: string | null;
  copy_suspicion?: { level: string; matches: unknown[] };
  similar_signatures?: Array<{ signature_id: string; document_id: string; score: number }>;
};

// validator-agent API `getDocumentRegions` item: a paragraph or table row of
// a text-layer page. `bbox` and `lines[].bbox` are [x0, y0, x1, y1], 0-1 of the
// page, origin top left; `lines[].start/end` are offsets into `text`.
export type UpstreamRegion = {
  region_id: string;
  page: number;
  kind?: string;
  label?: string | null;
  party?: string | null;
  refers_to?: string[] | null;
  summary?: string | null;
  section?: string | null;
  text: string;
  bbox?: number[] | null;
  lines?: Array<{ bbox: number[]; start: number; end: number }>;
};

// `status` is completed, not_run (no regions computed), failed or not_ready.
export type UpstreamRegions = {
  case_id: string;
  document_id: string;
  title?: string;
  document_label?: string;
  status: string;
  pages?: Array<{ page: number; width: number; height: number; source: string }>;
  regions?: UpstreamRegion[];
};

// errors: HTTP statuses the mock answers with instead of the data, so evals can
// cover upstream failures. A fixture without a client has a client_id that no
// client record has.
type Fixture = {
  case: UpstreamCase;
  client: UpstreamClient | null;
  errors?: { list_documents?: number };
  documents: Array<UpstreamDocument & { signatures: UpstreamSignature[]; errors?: { get?: number; signatures?: number } }>;
};

// eval-cases.json holds the mock-eval-* cases, generated by the case-evaluator's
// eval-cases/build.ts. Its cases list their documents by key into one shared
// table, because most of them reuse the same documents.
const EVAL_CASES = evalCases.cases.map((fixture) => ({
  ...fixture,
  documents: fixture.documents.map((key) => evalCases.documents[key as keyof typeof evalCases.documents]),
}));

export const FIXTURES: Record<string, Fixture> = Object.fromEntries(
  [solomRec, unhappy, stavbyFiser, ...EVAL_CASES].map((fixture) => [fixture.case.case_id, fixture as Fixture]),
);

export type Response<T> = { status: number; body: T | null };

export type AwsApi = {
  isMock: boolean;
  getCase(caseId: string): Promise<Response<UpstreamCase>>;
  listClients(nextToken?: string | null): Promise<Response<{ clients: UpstreamClient[]; next_token?: string | null }>>;
  listDocuments(caseId: string, nextToken?: string | null): Promise<Response<{ documents: UpstreamDocumentSummary[]; next_token?: string | null }>>;
  getDocument(caseId: string, documentId: string): Promise<Response<UpstreamDocument>>;
  getSignatures(caseId: string, documentId: string): Promise<Response<{ case_id: string; document_id: string; signatures: UpstreamSignature[] }>>;
  getRegions(caseId: string, documentId: string): Promise<Response<UpstreamRegions>>;
};

export function isAwsMock(context: GlobalsContext, caseId: string): boolean {
  return (
    caseId in FIXTURES ||
    isSwitchOn(context, AWS_MOCK) ||
    !getGlobalUrl(context, API_URL)
  );
}

export function getAwsApi(context: GlobalsContext, caseId: string): AwsApi {
  return isAwsMock(context, caseId) ? mockApi() : liveApi(context);
}

const notFound = { status: 404, body: null };

function mockApi(): AwsApi {
  return {
    isMock: true,
    async getCase(caseId) {
      const fixture = FIXTURES[caseId];
      return fixture ? { status: 200, body: fixture.case } : notFound;
    },
    async listClients() {
      const clients = Object.values(FIXTURES).flatMap((f) => (f.client ? [f.client] : []));
      return { status: 200, body: { clients, next_token: null } };
    },
    async listDocuments(caseId) {
      const fixture = FIXTURES[caseId];
      if (!fixture) return notFound;
      if (fixture.errors?.list_documents) return { status: fixture.errors.list_documents, body: null };
      const documents = fixture.documents.map(({ document_id, title, label, label_status, processing_status, page_count }) => ({
        document_id, title, label, label_status, processing_status, page_count,
      }));
      return { status: 200, body: { documents, next_token: null } };
    },
    async getDocument(caseId, documentId) {
      const document = FIXTURES[caseId]?.documents.find((d) => d.document_id === documentId);
      if (!document) return notFound;
      if (document.errors?.get) return { status: document.errors.get, body: null };
      const { signatures: _, errors: __, ...rest } = document;
      return { status: 200, body: { case_id: caseId, ...rest } };
    },
    async getSignatures(caseId, documentId) {
      const document = FIXTURES[caseId]?.documents.find((d) => d.document_id === documentId);
      if (!document) return notFound;
      if (document.errors?.signatures) return { status: document.errors.signatures, body: null };
      return { status: 200, body: { case_id: caseId, document_id: documentId, signatures: document.signatures } };
    },
    // Fixtures have no page geometry, so their regions are never computed.
    async getRegions(caseId, documentId) {
      const document = FIXTURES[caseId]?.documents.find((d) => d.document_id === documentId);
      if (!document) return notFound;
      return {
        status: 200,
        body: { case_id: caseId, document_id: documentId, title: document.title, document_label: document.label, status: "not_run", pages: [], regions: [] },
      };
    },
  };
}

function liveApi(context: GlobalsContext): AwsApi {
  const api = getGlobalUrl(context, API_URL);
  const page = (nextToken?: string | null) => (nextToken ? `?next_token=${encodeURIComponent(nextToken)}` : "");
  const id = encodeURIComponent;
  return {
    isMock: false,
    getCase: (caseId) => getJson(`${api}/cases/${id(caseId)}`, API_SECRET),
    listClients: (nextToken) => getJson(`${api}/clients${page(nextToken)}`, API_SECRET),
    listDocuments: (caseId, nextToken) => getJson(`${api}/cases/${id(caseId)}/documents${page(nextToken)}`, API_SECRET),
    getDocument: (caseId, documentId) => getJson(`${api}/cases/${id(caseId)}/documents/${id(documentId)}`, API_SECRET),
    getSignatures: (caseId, documentId) =>
      getJson(`${api}/cases/${id(caseId)}/documents/${id(documentId)}/signatures?match_client=true&include_vectors=false`, API_SECRET),
    getRegions: (caseId, documentId) =>
      getJson(`${api}/cases/${id(caseId)}/documents/${id(documentId)}/regions?include_geometry=true`, API_SECRET),
  };
}

// The runtime's fetch sometimes throws "NetworkError" before reaching the API,
// and an immediate retry succeeds, so each GET is retried once after a throw.
async function getJson<T>(url: string, secretName: string): Promise<Response<T>> {
  try {
    return await getJsonOnce<T>(url, secretName);
  } catch {
    return getJsonOnce<T>(url, secretName);
  }
}

async function getJsonOnce<T>(url: string, secretName: string): Promise<Response<T>> {
  const response = await fetch(url, {
    method: "GET",
    headers: { accept: "application/json" },
    secretName,
    timeoutMs: TIMEOUT_MS,
  } as RequestInit);
  const text = await response.text();
  let body: T | null = null;
  try {
    body = text ? JSON.parse(text) : null;
  } catch {
    body = null;
  }
  return { status: response.status, body };
}
